#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const [inputArg = "public/ascii/profile.ansi", outputArg = "app/profile-ansi.ts"] =
  process.argv.slice(2);

const inputPath = resolve(inputArg);
const outputPath = resolve(outputArg);
const ansi = readFileSync(inputPath, "utf8");
const moduleSource = `// Generated by scripts/sync-profile-ansi-module.mjs from ${inputArg}.\n// Keep this in sync with public/ascii/profile.ansi by running pnpm ascii:profile.\n\nexport const profileAnsi = ${JSON.stringify(ansi)};\n`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, moduleSource, "utf8");

console.log(`Synced ${outputPath} from ${inputPath}.`);
